import path from "node:path";
import type { StackDetection } from "./stackDetector.js";
import type { BuildConfig } from "../../services/buildConfigService.js";

export interface DockerfileGeneratorOptions {
  builder: "node" | "python" | "rust" | "go" | "static";
  packageManager?: string | null;
  buildCommand?: string | null;
  startCommand?: string | null;
  outputDirectory?: string | null;
  port?: number;
  framework?: string | null;
}

const DEFAULT_PORTS: Record<string, number> = {
  node: 3000,
  python: 8000,
  rust: 8080,
  go: 8080,
  static: 8080,
};

function sanitizeCommand(cmd: string | null | undefined): string | null {
  if (!cmd) return null;
  const trimmed = cmd.trim();
  if (trimmed.length === 0) return null;
  if (/[\r\n]/.test(trimmed)) {
    throw new Error("Command must not contain newline characters");
  }
  return trimmed;
}

function sanitizePort(port: unknown, defaultPort: number): number {
  if (typeof port === "number" && Number.isInteger(port) && port >= 1 && port <= 65535) {
    return port;
  }
  return defaultPort;
}

function formatStartCommand(startCmd: string | null, fallback: string): string {
  if (!startCmd) return fallback;
  if (startCmd.startsWith("[")) {
    try {
      const parsed = JSON.parse(startCmd);
      if (Array.isArray(parsed) && parsed.length > 0 && parsed.every((item) => typeof item === "string")) {
        return `CMD ${startCmd}`;
      }
    } catch {}
  }
  return `CMD ["sh", "-c", ${JSON.stringify(startCmd)}]`;
}

function formatCopySource(dir: string | null | undefined): string {
  if (!dir || dir === ".") return "COPY . .";
  const trimmed = dir.trim();
  if (/[\r\n]/.test(trimmed)) {
    throw new Error("Output directory must not contain newline characters");
  }
  if (/\s/.test(trimmed)) {
    return `COPY ["${trimmed.replace(/"/g, '\\"')}", "."]`;
  }
  return `COPY ${trimmed} .`;
}

export function generateNodeDockerfile(options: Partial<DockerfileGeneratorOptions> = {}): string {
  const pm = options.packageManager || "npm";
  const port = sanitizePort(options.port, DEFAULT_PORTS.node);
  const buildCmd = sanitizeCommand(options.buildCommand);
  const startCmd = sanitizeCommand(options.startCommand);

  let lockfileCopy = "COPY package*.json ./";
  let installCmd = "RUN npm ci";
  let fallbackStart = "CMD [\"npm\", \"start\"]";

  if (pm === "pnpm") {
    lockfileCopy = "COPY package.json pnpm-lock.yaml* ./\nRUN npm install -g pnpm";
    installCmd = "RUN pnpm install --frozen-lockfile";
    fallbackStart = "CMD [\"pnpm\", \"start\"]";
  } else if (pm === "yarn") {
    lockfileCopy = "COPY package.json yarn.lock* ./";
    installCmd = "RUN yarn install --frozen-lockfile";
    fallbackStart = "CMD [\"yarn\", \"start\"]";
  } else if (pm === "bun") {
    lockfileCopy = "COPY package.json bun.lock* bun.lockb* ./\nRUN npm install -g bun";
    installCmd = "RUN bun install --frozen-lockfile";
    fallbackStart = "CMD [\"bun\", \"run\", \"start\"]";
  }

  const runBuild = buildCmd ? `RUN ${buildCmd}` : "";
  const runStart = formatStartCommand(startCmd, fallbackStart);

  return `# Syntax: docker/dockerfile:1
# Multi-stage production build generated by DeployKit
# --- Stage 1: Build & Dependencies ---
FROM node:20-alpine AS builder
WORKDIR /app

RUN apk add --no-cache libc6-compat
${lockfileCopy}
${installCmd}

COPY . .
${runBuild ? `${runBuild}\n` : ""}
# --- Stage 2: Minimal Runtime ---
FROM node:20-alpine AS runner
WORKDIR /app

ENV NODE_ENV=production
ENV PORT=${port}

RUN addgroup --system --gid 10001 appgroup && \\
    adduser --system --uid 10001 appuser appgroup

COPY --from=builder --chown=appuser:appgroup /app ./

USER appuser
EXPOSE ${port}

${runStart}
`;
}

export function generatePythonDockerfile(options: Partial<DockerfileGeneratorOptions> = {}): string {
  const port = sanitizePort(options.port, DEFAULT_PORTS.python);
  const buildCmd = sanitizeCommand(options.buildCommand);
  const startCmd = sanitizeCommand(options.startCommand);
  const framework = options.framework;
  const pm = options.packageManager;

  let fallbackStart = `CMD ["python", "main.py"]`;
  if (framework === "fastapi") {
    fallbackStart = `CMD ["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "${port}"]`;
  } else if (framework === "flask") {
    fallbackStart = `CMD ["python", "-m", "flask", "run", "--host=0.0.0.0", "--port=${port}"]`;
  }

  const runBuild = buildCmd ? `RUN ${buildCmd}` : "";
  const runStart = formatStartCommand(startCmd, fallbackStart);

  let copyManifests = "COPY requirements*.txt pyproject*.toml Pipfile* ./";
  let installDeps = `RUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; \\
    elif [ -f pyproject.toml ]; then pip install --no-cache-dir .; \\
    elif [ -f Pipfile ]; then pip install --no-cache-dir pipenv && pipenv install --system --deploy; \\
    fi`;

  if (pm === "poetry") {
    copyManifests = "COPY pyproject.toml poetry.lock* ./";
    installDeps = "RUN pip install --no-cache-dir poetry && poetry config virtualenvs.create false && poetry install --no-root --no-interaction --no-ansi";
  } else if (pm === "pipenv") {
    copyManifests = "COPY Pipfile Pipfile.lock* ./";
    installDeps = "RUN pip install --no-cache-dir pipenv && pipenv install --system --deploy";
  }

  return `# Syntax: docker/dockerfile:1
# Multi-stage production build generated by DeployKit
# --- Stage 1: Build & Dependencies ---
FROM python:3.11-slim AS builder
WORKDIR /app

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

RUN apt-get update && apt-get install -y --no-install-recommends \\
    build-essential \\
    && rm -rf /var/lib/apt/lists/*

RUN python -m venv /opt/venv
ENV PATH="/opt/venv/bin:$PATH"

${copyManifests}
${installDeps}

COPY . .
${runBuild ? `${runBuild}\n` : ""}# --- Stage 2: Minimal Runtime ---
FROM python:3.11-slim AS runner
WORKDIR /app

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    PATH="/opt/venv/bin:$PATH" \\
    PORT=${port}

RUN groupadd -g 10001 appgroup && \\
    useradd -u 10001 -g appgroup -s /bin/sh -m appuser

COPY --from=builder --chown=appuser:appgroup /opt/venv /opt/venv
COPY --from=builder --chown=appuser:appgroup /app /app

USER appuser
EXPOSE ${port}

${runStart}
`;
}

export function generateRustDockerfile(options: Partial<DockerfileGeneratorOptions> = {}): string {
  const port = sanitizePort(options.port, DEFAULT_PORTS.rust);
  const buildCmd = sanitizeCommand(options.buildCommand);
  const startCmd = sanitizeCommand(options.startCommand);

  const runBuild = buildCmd ? `RUN ${buildCmd}` : "RUN cargo build --release";
  const runStart = formatStartCommand(
    startCmd,
    `CMD ["sh", "-c", "exec $(find /app -maxdepth 1 -type f -executable | head -n 1)"]`
  );

  return `# Syntax: docker/dockerfile:1
# Multi-stage production build generated by DeployKit
# --- Stage 1: Build Release Binary ---
FROM rust:1.76-alpine AS builder
WORKDIR /app

RUN apk add --no-cache musl-dev gcc make ca-certificates

COPY Cargo.toml Cargo.lock* ./
# Pre-build dummy to cache dependencies
RUN mkdir src && echo "fn main() {}" > src/main.rs && \\
    cargo build --release && \\
    rm -rf src

COPY . .
# Touch main.rs to invalidate dummy build and compile project
RUN if [ -f src/main.rs ]; then touch src/main.rs; fi
${runBuild}

RUN mkdir -p /app/dist && \\
    find target/release -maxdepth 1 -type f -executable -exec cp {} /app/dist/ \\;

# --- Stage 2: Minimal Runtime ---
FROM alpine:3.19 AS runner
WORKDIR /app

RUN apk add --no-cache ca-certificates tzdata && \\
    addgroup --system --gid 10001 appgroup && \\
    adduser --system --uid 10001 appuser appgroup

COPY --from=builder --chown=appuser:appgroup /app/dist /app

USER appuser
EXPOSE ${port}

${runStart}
`;
}

export function generateGoDockerfile(options: Partial<DockerfileGeneratorOptions> = {}): string {
  const port = sanitizePort(options.port, DEFAULT_PORTS.go);
  const buildCmd = sanitizeCommand(options.buildCommand);
  const startCmd = sanitizeCommand(options.startCommand);

  let runBuild: string;
  if (buildCmd) {
    if (buildCmd.startsWith("go build")) {
      runBuild = `RUN CGO_ENABLED=0 GOOS=linux ${buildCmd}`;
    } else {
      runBuild = `RUN ${buildCmd}`;
    }
  } else {
    runBuild = 'RUN CGO_ENABLED=0 GOOS=linux go build -ldflags="-w -s" -o /app/server .';
  }

  const runStart = formatStartCommand(startCmd, 'CMD ["/app/server"]');

  return `# Syntax: docker/dockerfile:1
# Multi-stage production build generated by DeployKit
# --- Stage 1: Compile Go Binary ---
FROM golang:1.22-alpine AS builder
WORKDIR /app

RUN apk add --no-cache ca-certificates git

COPY go.mod go.sum* ./
RUN go mod download

COPY . .
${runBuild}

# --- Stage 2: Minimal Runtime ---
FROM alpine:3.19 AS runner
WORKDIR /app

RUN apk add --no-cache ca-certificates tzdata && \\
    addgroup --system --gid 10001 appgroup && \\
    adduser --system --uid 10001 appuser appgroup

COPY --from=builder --chown=appuser:appgroup /app/server /app/server

USER appuser
EXPOSE ${port}

${runStart}
`;
}

export function generateStaticDockerfile(options: Partial<DockerfileGeneratorOptions> = {}): string {
  const port = sanitizePort(options.port, DEFAULT_PORTS.static);
  const copyInstruction = formatCopySource(options.outputDirectory);
  const portConfig = port !== 8080
    ? `RUN sed -i -E 's/listen\\s+8080;/listen ${port};/g' /etc/nginx/conf.d/default.conf\n`
    : "";

  return `# Syntax: docker/dockerfile:1
# Multi-stage production build generated by DeployKit
# Static site served via Nginx unprivileged
FROM nginxinc/nginx-unprivileged:alpine AS runner
WORKDIR /usr/share/nginx/html

${portConfig}${copyInstruction}

EXPOSE ${port}
CMD ["nginx", "-g", "daemon off;"]
`;
}

export function generateDockerfileForStack(
  detection: StackDetection,
  overrideConfig?: Partial<BuildConfig> | null,
  port?: number
): string {
  const builder = (overrideConfig?.builder || detection.kind) as DockerfileGeneratorOptions["builder"];
  const packageManager = detection.packageManager;
  const buildCommand = overrideConfig?.buildCommand ?? detection.buildCommand;
  const startCommand = overrideConfig?.startCommand ?? detection.startCommand;
  const outputDirectory = overrideConfig?.outputDirectory ?? detection.outputDirectory;
  const framework = detection.framework;

  const options: DockerfileGeneratorOptions = {
    builder,
    packageManager,
    buildCommand,
    startCommand,
    outputDirectory,
    port,
    framework,
  };

  switch (builder) {
    case "node":
      return generateNodeDockerfile(options);
    case "python":
      return generatePythonDockerfile(options);
    case "rust":
      return generateRustDockerfile(options);
    case "go":
      return generateGoDockerfile(options);
    case "static":
      return generateStaticDockerfile(options);
    default:
      throw new Error(`Unsupported builder for Dockerfile generation: ${builder}`);
  }
}
